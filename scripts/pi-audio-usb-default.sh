#!/usr/bin/env bash
# Run on the Raspberry Pi as the kiosk user (same account as labwc, usually admin).
#
# Priority:
#   1) pactl: USB (non-HDMI) sink + optional USB source → PULSE_SINK / PULSE_SOURCE.
#   2) wpctl only: USB sink + optional USB capture source (3.5mm mic-in on same dongle).
#   3) ALSA-only: ~/.asoundrc + playback/capture unmute + ALSA_CARD in s52-carplay-audio.env.
#
# From your Mac (do NOT run this script locally on macOS — no amixer/pi ALSA stack):
#   S52_HOST=192.168.1.96 ./scripts/ssh-pi.sh 'bash -s' < scripts/pi-audio-usb-default.sh
set -euo pipefail

if [[ "$(uname -s)" != Linux ]]; then
  echo "This script must run on the Pi (Linux), not on $(uname -s)." >&2
  echo "From your Mac:  S52_HOST=192.168.x.x ./scripts/ssh-pi.sh 'bash -s' < scripts/pi-audio-usb-default.sh" >&2
  exit 1
fi

USB_CARD="${S52_USB_ALSA_CARD:-${ALSA_CARD:-Audio}}"

usb_extension_unmute() {
  if ! command -v amixer &>/dev/null; then
    return 0
  fi
  if ! amixer -c "${USB_CARD}" info &>/dev/null; then
    return 0
  fi
  amixer -c "${USB_CARD}" sset PCM 100% >/dev/null 2>&1 || true
  amixer -c "${USB_CARD}" sset 'Extension Unit' on >/dev/null 2>&1 || true
}

# Simple 3.5mm electret / line mic on a USB sound card: unmute common ALSA capture controls.
usb_capture_unmute() {
  if ! command -v amixer &>/dev/null; then
    return 0
  fi
  if ! amixer -c "${USB_CARD}" info &>/dev/null; then
    return 0
  fi
  local c="${USB_CARD}"
  amixer -c "$c" sset Capture 90% >/dev/null 2>&1 || true
  amixer -c "$c" sset Capture cap >/dev/null 2>&1 || true
  amixer -c "$c" sset Capture on >/dev/null 2>&1 || true
  amixer -c "$c" sset 'Mic Capture' 90% >/dev/null 2>&1 || true
  amixer -c "$c" sset 'Mic Capture' cap >/dev/null 2>&1 || true
  amixer -c "$c" sset Mic 90% >/dev/null 2>&1 || true
  amixer -c "$c" sset 'Auto Gain Control' off >/dev/null 2>&1 || true
}

write_env_carplay_audio() {
  local sink_name="$1"
  local source_name="${2:-}"
  local env_file="${HOME}/.config/s52-carplay-audio.env"
  local mode="" bt_sink=""
  # Preserve the Settings-chosen output mode across reinstalls — in bluetooth
  # mode PULSE_SINK stays unset so apps follow the PipeWire default sink and
  # fall back to the USB DAC when the stereo drops (see scripts/s52-bluetooth.sh).
  if [[ -f "${env_file}" ]]; then
    mode="$(sed -n 's/^export S52_AUDIO_OUTPUT=//p' "${env_file}" | head -1)"
  fi
  mkdir -p "${HOME}/.config"
  {
    echo "# Generated by pi-audio-usb-default.sh — $(date -Iseconds)"
    printf 'export S52_AUX_SINK=%q\n' "${sink_name}"
    if [[ "${mode}" == "bluetooth" ]]; then
      echo "export S52_AUDIO_OUTPUT=bluetooth"
    else
      echo "export S52_AUDIO_OUTPUT=aux"
      printf 'export PULSE_SINK=%q\n' "${sink_name}"
    fi
    echo "export ALSA_CARD=${USB_CARD}"
    if [[ -n "${source_name}" ]]; then
      printf 'export PULSE_SOURCE=%q\n' "${source_name}"
    fi
  } >"${env_file}"
  chmod 600 "${env_file}"
  # Bluetooth mode: the USB set-default above stole the default sink — give it
  # back to the connected stereo (the USB DAC stays the automatic fallback).
  if [[ "${mode}" == "bluetooth" ]] && command -v pactl &>/dev/null; then
    bt_sink="$(pactl list sinks short 2>/dev/null | awk '{print $2}' | grep -m1 '^bluez_' || true)"
    if [[ -n "${bt_sink}" ]]; then
      pactl set-default-sink "${bt_sink}" 2>/dev/null || true
    fi
  fi
  echo "Wrote ${env_file}"
  echo "Restart kiosk: sudo systemctl restart s52-cage-kiosk"
}

alsa_usb_fix() {
  echo "=== ALSA-only path — card ${USB_CARD} ==="
  if ! command -v amixer &>/dev/null; then
    echo "amixer missing; install: sudo apt-get install -y alsa-utils" >&2
    return 1
  fi
  if ! amixer -c "${USB_CARD}" info &>/dev/null; then
    echo "No ALSA card '${USB_CARD}'. aplay -l:" >&2
    aplay -l >&2 || true
    return 1
  fi
  usb_extension_unmute
  usb_capture_unmute
  mkdir -p "${HOME}/.config"
  cat >"${HOME}/.asoundrc" <<EOF
# S52: default playback to USB DAC (see aplay -l).
pcm.!default {
    type plug
    slave.pcm "hw:${USB_CARD},0"
}
ctl.!default {
    type hw
    card ${USB_CARD}
}
EOF
  chmod 644 "${HOME}/.asoundrc"
  {
    echo "# Generated by pi-audio-usb-default.sh — $(date -Iseconds)"
    echo "export ALSA_CARD=${USB_CARD}"
  } >"${HOME}/.config/s52-carplay-audio.env"
  chmod 600 "${HOME}/.config/s52-carplay-audio.env"
  echo "Wrote ~/.asoundrc and ~/.config/s52-carplay-audio.env"
  echo "Optional once: sudo alsactl store"
  echo "Restart kiosk: sudo systemctl restart s52-cage-kiosk"
}

wpctl_usb_sink_id() {
  # Match sink line only (not "Devices" 48. USB Audio): must include "Analog".
  wpctl status 2>/dev/null | grep 'USB Audio Analog' | head -1 | grep -oE '[0-9]+' | head -1
}

wpctl_usb_source_id() {
  local id
  id="$(wpctl status 2>/dev/null | sed -n '/Sources:/,/Filters:/p' | grep 'USB Audio' | head -1 | grep -oE '[0-9]+' | head -1)"
  if [[ -n "${id}" ]]; then
    echo "${id}"
    return
  fi
  wpctl status 2>/dev/null | sed -n '/Sources:/,/Streams:/p' | grep 'USB Audio' | head -1 | grep -oE '[0-9]+' | head -1
}

wpctl_pipewire_usb_fix() {
  echo "=== PipeWire (wpctl) — USB playback (+ capture if present) ==="
  local sid name rid rname
  sid="$(wpctl_usb_sink_id)"
  if [[ -z "${sid}" ]]; then
    echo "Could not find USB Audio sink in: wpctl status" >&2
    wpctl status >&2 || true
    return 1
  fi
  wpctl set-default "${sid}" 2>/dev/null || true
  wpctl set-volume "${sid}" 100% unmute 2>/dev/null || true
  name="$(wpctl inspect "${sid}" 2>/dev/null | sed -n 's/^  \* node.name = "\(.*\)"/\1/p' | head -1)"
  if [[ -z "${name}" ]]; then
    echo "wpctl inspect ${sid} did not yield node.name" >&2
    return 1
  fi
  echo "Default sink id=${sid}  PULSE_SINK=${name}"

  rname=""
  rid="$(wpctl_usb_source_id || true)"
  if [[ -n "${rid}" ]]; then
    wpctl set-default "${rid}" 2>/dev/null || true
    wpctl set-volume "${rid}" 100% unmute 2>/dev/null || true
    rname="$(wpctl inspect "${rid}" 2>/dev/null | sed -n 's/^  \* node.name = "\(.*\)"/\1/p' | head -1)"
    if [[ -n "${rname}" ]]; then
      echo "Default source id=${rid}  PULSE_SOURCE=${rname}"
    fi
  else
    echo "(No USB capture device in PipeWire — output-only dongle, or mic not plugged.)"
  fi

  usb_extension_unmute
  usb_capture_unmute
  write_env_carplay_audio "${name}" "${rname}"
  if command -v pactl &>/dev/null; then
    pactl set-default "${name}" 2>/dev/null || true
    [[ -n "${rname}" ]] && pactl set-default-source "${rname}" 2>/dev/null || true
    echo "Current default (pactl): sink=$(pactl get-default-sink 2>/dev/null || echo n/a) source=$(pactl get-default-source 2>/dev/null || echo n/a)"
  fi
}

if command -v pactl &>/dev/null; then
  pick_sink() {
    local line
    while read -r line; do
      case $(echo "$line" | tr '[:upper:]' '[:lower:]') in
        *hdmi* | *vc4hdmi*) continue ;;
      esac
      case $(echo "$line" | tr '[:upper:]' '[:lower:]') in
        *usb* | *dac* | *cmedia* | *c-media* | *fosi* | *sabrent* | *ugreen* | *generic_usb*)
          echo "$line" | awk '{print $2}'
          return 0
          ;;
      esac
    done < <(pactl list sinks short)

    while read -r line; do
      case $(echo "$line" | tr '[:upper:]' '[:lower:]') in
        *hdmi* | *vc4hdmi*) continue ;;
      esac
      echo "$line" | awk '{print $2}'
      return 0
    done < <(pactl list sinks short)

    return 1
  }

  pick_source() {
    local line
    while read -r line; do
      case $(echo "$line" | tr '[:upper:]' '[:lower:]') in
        *monitor* | *hdmi*) continue ;;
      esac
      case $(echo "$line" | tr '[:upper:]' '[:lower:]') in
        *usb* | *dac* | *cmedia* | *c-media* | *fosi* | *sabrent* | *ugreen* | *generic_usb*)
          echo "$line" | awk '{print $2}'
          return 0
          ;;
      esac
    done < <(pactl list sources short)

    while read -r line; do
      case $(echo "$line" | tr '[:upper:]' '[:lower:]') in
        *monitor* | *hdmi*) continue ;;
      esac
      echo "$line" | awk '{print $2}'
      return 0
    done < <(pactl list sources short)

    return 1
  }

  SINK_NAME="$(pick_sink || true)"
  if [[ -z "${SINK_NAME:-}" ]]; then
    echo "No Pulse sink matched; trying wpctl USB sink…" >&2
    wpctl_pipewire_usb_fix || alsa_usb_fix
    exit 0
  fi

  SOURCE_NAME="$(pick_source || true)"

  echo "Using Pulse default sink: ${SINK_NAME}"
  pactl set-default "${SINK_NAME}"
  if [[ -n "${SOURCE_NAME:-}" ]]; then
    echo "Using Pulse default source: ${SOURCE_NAME}"
    pactl set-default-source "${SOURCE_NAME}"
  fi
  if command -v wpctl &>/dev/null; then
    wpctl set-volume @DEFAULT_AUDIO_SINK@ 100% unmute 2>/dev/null || true
    wpctl set-volume @DEFAULT_AUDIO_SOURCE@ 100% unmute 2>/dev/null || true
  fi
  usb_extension_unmute
  usb_capture_unmute
  write_env_carplay_audio "${SINK_NAME}" "${SOURCE_NAME:-}"
  echo "Current default sink: $(pactl get-default-sink)"
  echo "Current default source: $(pactl get-default-source 2>/dev/null || echo n/a)"
  exit 0
fi

if command -v wpctl &>/dev/null && wpctl status 2>/dev/null | grep -q 'USB Audio'; then
  wpctl_pipewire_usb_fix
  exit 0
fi

alsa_usb_fix
